import assert from 'node:assert/strict';
import {expect} from '@playwright/test';

export async function verifySculpture(browser,base){
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await expect(page.locator('.hero-art')).toHaveAttribute('data-sculpture-state','ready');
  await page.waitForTimeout(3500);
  const view=page.locator('.sculpture-viewport');
  const image=()=>view.screenshot({animations:'disabled'});
  const assembled=await image();
  await page.screenshot({path:'test-results/screenshots/sculpture-desktop.png'});
  await page.getByRole('button',{name:'Titanium',exact:true}).click();
  await expect(page.getByRole('button',{name:'Titanium',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.waitForTimeout(250);
  assert.notEqual(Buffer.compare(assembled,await image()),0,'Finish must change the rendered sculpture');
  await page.screenshot({path:'test-results/screenshots/sculpture-titanium.png'});
  await page.getByRole('button',{name:'Separate layers',exact:true}).click();
  await page.waitForTimeout(1200);
  await expect(page.getByRole('button',{name:'Join layers',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.screenshot({path:'test-results/screenshots/sculpture-layers.png'});
  const split=await image();const box=await view.boundingBox();
  await page.mouse.move(box.x+box.width*.5,box.y+box.height*.5);
  await page.mouse.down();await page.mouse.move(box.x+box.width*.5+150,box.y+box.height*.5+40,{steps:12});await page.mouse.up();
  await page.waitForTimeout(900);
  assert.notEqual(Buffer.compare(split,await image()),0,'Drag must rotate the actual model');
  await view.focus();const beforeKey=await image();await page.keyboard.press('ArrowLeft');await page.waitForTimeout(900);
  assert.notEqual(Buffer.compare(beforeKey,await image()),0,'Keyboard must rotate the actual model');
  await page.getByRole('button',{name:'Reset sculpture view'}).click();
  await expect(page.getByRole('button',{name:'Separate layers',exact:true})).toHaveAttribute('aria-pressed','false');
  await page.getByRole('button',{name:'Pearl',exact:true}).click();
  await page.evaluate(()=>{const t=window.ScrollTrigger.getById('hero-story');window.scrollTo({top:t.end-50,behavior:'instant'})});
  await page.waitForTimeout(1500);
  await page.screenshot({path:'test-results/screenshots/sculpture-scroll.png'});
  assert.ok(Number(await page.locator('.hero').getAttribute('data-scene-progress'))>.9);
  await page.getByRole('link',{name:'Skip to selected work'}).click();
  const work=page.locator('.work-visual').first();await work.hover();
  const r=await work.boundingBox();await page.mouse.move(r.x+r.width*.8,r.y+r.height*.3);await page.waitForTimeout(500);
  assert.notEqual(await page.locator('.frame-tilt').first().evaluate(e=>getComputedStyle(e).transform),'matrix(1, 0, 0, 1, 0, 0)');
  const start=await page.evaluate(()=>scrollY);
  await page.mouse.move(r.x+r.width*.7,r.y+r.height*.5);await page.mouse.down();
  await page.mouse.move(r.x+r.width*.7-340,r.y+r.height*.5,{steps:14});await page.mouse.up();
  await page.waitForTimeout(1100);
  assert.ok(await page.evaluate(()=>scrollY)>start+200,'Gallery drag must advance the scroll position');
  assert.equal(new URL(page.url()).pathname,'/','Dragging must not open a case study');
  await page.getByRole('button',{name:'Show eCitizen'}).focus();await page.keyboard.press('ArrowRight');
  await expect(page.locator('.gallery-current')).toHaveText('02');
  await page.setViewportSize({width:390,height:844});
  await expect(page.locator('.pin-spacer')).toHaveCount(0);
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await view.scrollIntoViewIfNeeded();await page.waitForTimeout(900);
  assert.equal(await page.locator('body').evaluate(e=>e.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'test-results/screenshots/sculpture-mobile.png'});
  await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(500);
  const still=await image();await page.waitForTimeout(500);
  assert.equal(Buffer.compare(still,await image()),0,'Reduced-motion sculpture must stay still');
  await page.getByRole('button',{name:'Titanium',exact:true}).click();await page.waitForTimeout(200);
  assert.notEqual(Buffer.compare(still,await image()),0,'Manual finish control must still work with reduced motion');
  await page.evaluate(()=>{window.lostExtension=document.querySelector('.sculpture-canvas').getContext('webgl2').getExtension('WEBGL_lose_context');window.lostExtension.loseContext()});
  await expect(page.locator('.hero-art')).toHaveAttribute('data-sculpture-state','fallback');
  await expect(page.locator('.sculpture')).toBeVisible();
  await page.evaluate(()=>window.lostExtension.restoreContext());
  await expect(page.locator('.hero-art')).toHaveAttribute('data-sculpture-state','ready');
  assert.deepEqual(errors,[]);await page.close();

  const fallback=await browser.newPage();
  await fallback.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){if(type.includes('webgl'))return null;return original.call(this,type,...args)}});
  await fallback.goto(base);
  await expect(fallback.locator('.hero-art')).toHaveAttribute('data-sculpture-state','fallback');
  await expect(fallback.locator('.sculpture')).toBeVisible();await fallback.close();
  console.log('PASS: WebGL rendering, pearl/titanium finishes, layer separation, mouse/keyboard rotation, reset, scroll-synced model, gallery drag/tilt, mobile, reduced-motion stillness, and WebGL failure/recovery.');
}
